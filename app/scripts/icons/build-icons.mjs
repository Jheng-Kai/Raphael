// from Feather, MIT; both notices in app/scripts/release-licenses/lucide-static-1.61.0-LICENSE.txt). The app ships the
// generated module, never the package. Run `node scripts/icons/build-icons.mjs` after changing the map or the version.
import { readFileSync, writeFileSync } from "node:fs";

/** The app's icon names and the Lucide icon each one draws. */
const MAP = {
  menu: "menu", sidebar: "panel-left", person: "user", crown: "crown", reply: "reply", pin: "pin", eyeOff: "eye-off",
  home: "house", clock: "clock", book: "book", down: "chevron-down", up: "chevron-up", plus: "plus", copy: "copy",
  trash: "trash-2", search: "search", x: "x", gear: "settings", mic: "mic", wallet: "wallet", sparkle: "sparkle",
  info: "info", lock: "lock", left: "chevron-left", right: "chevron-right", refresh: "refresh-cw", link: "link",
  chat: "message-square", globe: "globe", monitor: "monitor", expand: "maximize", open: "maximize-2", shrink: "minimize-2",
  eye: "eye", shield: "shield", star: "star", grid: "layout-grid", check: "check", sliders: "sliders-horizontal",
  keyboard: "keyboard", cloud: "cloud", send: "arrow-up", stop: "square", bot: "bot", pencil: "pencil", share: "share", steps: "list",
  plug: "plug", bell: "bell", calendar: "calendar", news: "newspaper", folder: "folder", memory: "brain", attach: "paperclip",
  voice: "audio-lines", database: "database", smile: "smile", smilePlus: "smile-plus", play: "play", pause: "pause",
  external: "external-link", minus: "minus", image: "image", file: "file", download: "download", more: "ellipsis",
  repeat: "repeat", mail: "mail", swap: "arrow-left-right", report: "file-chart-column",
};

const root = new URL("../../", import.meta.url);
const version = JSON.parse(readFileSync(new URL("node_modules/lucide-static/package.json", root), "utf8")).version;
const entries = Object.entries(MAP).map(([name, lucide]) => {
  const svg = readFileSync(new URL(`node_modules/lucide-static/icons/${lucide}.svg`, root), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "").replace(/\s*\n\s*/g, "").replace(/\s+\/>/g, "/>").trim();
  if (!inner || /<(?!\/?(?:path|circle|rect|line|polyline|polygon|ellipse)\b)/.test(inner)) throw new Error(`${lucide}: unexpected markup`);
  return `  ${/^[a-z][A-Za-z]*$/.test(name) ? name : JSON.stringify(name)}: ${JSON.stringify(inner)},`;
});
writeFileSync(new URL("src/main/icon-set.ts", root), `// Generated by scripts/icons/build-icons.mjs from lucide-static ${version} (ISC; see app/scripts/release-licenses/lucide-static-1.61.0-LICENSE.txt). Do not edit.
/** Each icon's drawing inside a 24 x 24 view box, stroked by \`svg.i\` (styles.css). */
export const ICON = {
${entries.join("\n")}
} as const;
`);
console.log(`icon-set.ts: ${entries.length} icons from lucide-static ${version}`);

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export function motionSource(css) {
  css = css.replace(/\r\n/g,'\n');
  const frames = [...css.matchAll(/@keyframes\s+(slime-(?!loop-)[\w-]+)\s*\{((?:[^{}]|\{[^{}]*\})*)\}/g)].map(match => match[0]);
  const eyes = [...css.matchAll(/\.slime(?:\[data-state="[\w-]+"\])? \{ --eye[^}]+\}/g)].map(match => match[0]);
  return [...eyes,...frames].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = motionSource(readFileSync(new URL('../src/main/slime.css',import.meta.url),'utf8'));
  writeFileSync(new URL('../src/main/slime-motion-data.ts',import.meta.url), `// Generated by node scripts/slime-cels.mjs from slime.css.\nexport default ${JSON.stringify(source,null,2)};\n`);
}
